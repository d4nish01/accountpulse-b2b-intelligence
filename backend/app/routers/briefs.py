"""AI research-brief endpoints.

If GEMINI_API_KEY is set, briefs are generated by the Gemini API.
Without a key the endpoint still works and returns a structured
template brief built from the company's own data - the app degrades
gracefully instead of failing.
"""
import os

import requests
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from ..database import get_db
from ..models import Company, Brief
from ..schemas import BriefOut

router = APIRouter(prefix="/briefs", tags=["briefs"])

# Preferred model first, then a lite fallback: free-tier flash models often
# return 503 under load, so we try in order before degrading to the template.
GEMINI_MODELS = ["gemini-flash-latest", "gemini-flash-lite-latest"]
GEMINI_URL = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"


def build_prompt(company: Company) -> str:
    signals = ", ".join(company.signal_list()) or "none recorded"
    return (
        "You are a B2B sales-intelligence analyst. Write a short, factual account "
        "research brief for the company below. Use exactly these sections:\n"
        "1. What they do\n2. Why they might buy (fit signals)\n"
        "3. Suggested first touch (one paragraph a rep could send)\n\n"
        f"Company: {company.name}\nDomain: {company.domain}\n"
        f"Industry: {company.industry} / {company.sub_industry}\n"
        f"Employees: {company.employee_count}\nRevenue: ${company.revenue_musd:.0f}M\n"
        f"Location: {company.country} ({company.region})\nSignals: {signals}\n"
        f"Notes: {company.description}\n"
        "Keep it under 250 words. If you are unsure of a fact, say so."
    )


def template_brief(company: Company) -> str:
    """Fallback brief when no LLM API key is configured."""
    signals = ", ".join(company.signal_list()) or "none recorded"
    return (
        f"## {company.name} - Account Brief (template mode)\n\n"
        f"**What they do:** {company.description or 'No description on record.'}\n\n"
        f"**Firmographics:** {company.industry} / {company.sub_industry}, "
        f"{company.employee_count} employees, ${company.revenue_musd:.0f}M revenue, "
        f"based in {company.country} ({company.region}).\n\n"
        f"**Recorded signals:** {signals}.\n\n"
        f"**Next step:** configure GEMINI_API_KEY to replace this template with a "
        f"full AI-generated brief."
    )


@router.post("/{company_id}", response_model=BriefOut)
def generate_brief(company_id: int, db: Session = Depends(get_db)):
    company = db.get(Company, company_id)
    if not company:
        raise HTTPException(status_code=404, detail="Company not found")

    api_key = os.getenv("GEMINI_API_KEY", "").strip()
    content, model = None, "template"
    if api_key:
        for candidate in GEMINI_MODELS:
            try:
                resp = requests.post(
                    GEMINI_URL.format(model=candidate),
                    params={"key": api_key},
                    json={"contents": [{"parts": [{"text": build_prompt(company)}]}]},
                    timeout=30,
                )
                resp.raise_for_status()
                content = resp.json()["candidates"][0]["content"]["parts"][0]["text"]
                model = candidate
                break
            except (requests.RequestException, KeyError, IndexError):
                continue  # try the next model, then the template
    if content is None:
        # Never let an LLM outage break the product - fall back to template.
        content = template_brief(company)

    brief = Brief(company_id=company.id, content=content, model=model)
    db.add(brief)
    db.commit()
    db.refresh(brief)
    return brief


@router.get("/{company_id}", response_model=list[BriefOut])
def list_briefs(company_id: int, db: Session = Depends(get_db)):
    return (
        db.query(Brief)
        .filter(Brief.company_id == company_id)
        .order_by(Brief.created_at.desc())
        .all()
    )
